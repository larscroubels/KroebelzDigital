function switchLanguage(lang) {
  localStorage.setItem("language", lang);
  
  // Update buttons
  document.querySelectorAll(".lang-btn").forEach(btn => {
    btn.classList.remove("active");
    if (btn.dataset.lang === lang) {
      btn.classList.add("active");
    }
  });

  // Update links and elements with data attributes
  document.querySelectorAll("[data-nl][data-en]").forEach(el => {
    if (lang === "nl") {
      el.textContent = el.dataset.nl;
      if (el.placeholder) {
        el.placeholder = el.dataset.nl;
      }
    } else {
      el.textContent = el.dataset.en;
      if (el.placeholder) {
        el.placeholder = el.dataset.en;
      }
    }
  });

  // Update other text content
  document.querySelectorAll("*").forEach(el => {
    if (el.children.length === 0 && el.textContent.trim()) {
      const text = el.textContent.trim();
      const source = lang === "nl" ? "en" : "nl";
      const target = lang === "nl" ? "nl" : "en";
      
      if (source === "en" && translations.nl[text]) {
        el.textContent = translations[target][text];
      } else if (source === "nl" && translations.en[text]) {
        el.textContent = translations[target][text];
      }
    }
  });
}

document.addEventListener("DOMContentLoaded", () => {
  // Initialize language
  const savedLanguage = localStorage.getItem("language") || "nl";
  
  // Set initial language buttons
  document.querySelectorAll(".lang-btn").forEach(btn => {
    if (btn.dataset.lang === savedLanguage) {
      btn.classList.add("active");
    } else {
      btn.classList.remove("active");
    }
  });

  // Add language switch listeners
  document.querySelectorAll(".lang-btn").forEach(btn => {
    btn.addEventListener("click", () => {
      const lang = btn.dataset.lang;
      switchLanguage(lang);
    });
  });

  const year = document.getElementById("year");
  if (year) year.textContent = new Date().getFullYear();

  // Hide navbar on scroll down, show on scroll up
  const navbar = document.querySelector(".navbar");
  let lastScrollTop = 0;
  
  window.addEventListener("scroll", () => {
    const scrollTop = window.pageYOffset || document.documentElement.scrollTop;
    
    if (scrollTop > lastScrollTop && scrollTop > 100) {
      // Scrolling down
      navbar.style.transform = "translateY(-100%)";
      navbar.style.transition = "transform 0.3s ease-in-out";
    } else {
      // Scrolling up
      navbar.style.transform = "translateY(0)";
      navbar.style.transition = "transform 0.3s ease-in-out";
    }
    lastScrollTop = scrollTop <= 0 ? 0 : scrollTop;
  });

  // Close the mobile menu after a navigation link is selected.
  document.querySelectorAll("#mainNav .nav-link, #mainNav .btn").forEach((link) => {
    link.addEventListener("click", () => {
      const menu = document.getElementById("mainNav");
      if (menu && menu.classList.contains("show") && window.bootstrap) {
        window.bootstrap.Collapse.getOrCreateInstance(menu).hide();
      }
    });
  });

  // The static site prepares an email in the visitor's mail app.
  const form = document.getElementById("contactForm");
  if (form) {
    form.addEventListener("submit", (event) => {
      event.preventDefault();
      if (!form.reportValidity()) return;

      const data = new FormData(form);
      const name = String(data.get("name") || "").trim();
      const email = String(data.get("email") || "").trim();
      const project = String(data.get("project") || "Website enquiry");
      const message = String(data.get("message") || "").trim();
      
      // Get current language from active button
      const activeBtn = document.querySelector(".lang-btn.active");
      const currentLang = activeBtn ? activeBtn.dataset.lang : (localStorage.getItem("language") || "nl");
      
      let subject, body, statusMessage;
      if (currentLang === "nl") {
        subject = encodeURIComponent(`Website aanvraag: ${project}`);
        body = encodeURIComponent(
          `Hallo Lars,\n\nIk wil graag contact met je opnemen over een project.\n\nNaam: ${name}\nE-mail: ${email}\nProject: ${project}\n\nBericht:\n${message}\n\nMet vriendelijke groeten,\n${name}`
        );
        statusMessage = "Je e-mailapp opent met je bericht klaar. Stuur de e-mail om je aanvraag in te dienen.";
      } else {
        subject = encodeURIComponent(`Website enquiry: ${project}`);
        body = encodeURIComponent(
          `Hi Lars,\n\nI'd like to get in touch about a project.\n\nName: ${name}\nEmail: ${email}\nProject: ${project}\n\nMessage:\n${message}\n\nKind regards,\n${name}`
        );
        statusMessage = "Your email app should open with your message ready. Please send the email to complete your enquiry.";
      }

      const status = document.getElementById("formStatus");
      if (status) status.textContent = statusMessage;
      window.location.href = `mailto:info@kroebelzdigital.be?subject=${subject}&body=${body}`;
    });
  }
});
